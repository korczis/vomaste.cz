// In-browser SQL console over the published registries (DuckDB-Wasm).
//
// See docs/adr/duckdb-wasm-and-sigma.md. The point is not speed — the whole
// dataset is under 200 rows — it is that a reader can interrogate the data
// instead of trusting the site's own summary tiles.
//
// Three rules this file keeps:
//   1. NOTHING is downloaded until the visitor presses the start button. The
//      DuckDB bundle is several MB, so it must never touch the initial page
//      load; the button states the cost before it is paid.
//   2. It is a read-only projection. The tables come from /data/*.json,
//      generated by scripts/dossier/build-data-exports.mjs from the same
//      front matter the pages render from — no status, score or rating is
//      computed here.
//   3. Failure is honest and non-fatal: if the CDN is blocked or WASM is
//      unavailable, the console says so and points at the plain JSON files,
//      which stay downloadable. No record is reachable *only* through this.
const DUCKDB_VERSION = "1.29.0";
const CDN = `https://cdn.jsdelivr.net/npm/@duckdb/duckdb-wasm@${DUCKDB_VERSION}/+esm`;
const TABLES = ["claims", "sources", "cases", "gaps", "relations", "entities", "dossiers"];

let dbPromise = null;

async function initDuckDb(log) {
  // The import specifier is built at runtime on purpose: esbuild only bundles
  // static string literals, so this stays a genuine lazy network import
  // instead of being pulled into static/js/app.js.
  const url = CDN;
  log("Stahuji DuckDB-Wasm…");
  const duckdb = await import(/* @vite-ignore */ url);
  const bundle = await duckdb.selectBundle(duckdb.getJsDelivrBundles());
  const workerUrl = URL.createObjectURL(
    new Blob([`importScripts("${bundle.mainWorker}");`], { type: "text/javascript" }),
  );
  const worker = new Worker(workerUrl);
  const db = new duckdb.AsyncDuckDB(new duckdb.ConsoleLogger(duckdb.LogLevel.WARNING), worker);
  await db.instantiate(bundle.mainModule, bundle.pthreadWorker);
  URL.revokeObjectURL(workerUrl);

  const conn = await db.connect();
  log("Načítám tabulky…");
  for (const t of TABLES) {
    const res = await fetch(`/data/${t}.json`);
    if (!res.ok) continue;
    await db.registerFileText(`${t}.json`, await res.text());
    await conn.query(`CREATE OR REPLACE VIEW ${t} AS SELECT * FROM read_json_auto('${t}.json')`);
  }
  log("");
  return conn;
}

// Result rendering builds DOM nodes and sets textContent — never innerHTML.
// Query results are strings the visitor's own SQL produced; going through
// text nodes means no amount of quoting cleverness in a value can turn into
// markup or an attribute, and internal links are recognised by an explicit
// same-origin path test rather than by pattern-matching a string into HTML.
function renderTable(el, rows) {
  el.replaceChildren();
  if (!rows.length) {
    const p = document.createElement("p");
    p.className = "p-4 text-sm text-white/50";
    p.textContent = "Dotaz nevrátil žádný řádek.";
    el.append(p);
    return;
  }
  const cols = Object.keys(rows[0]);
  const table = document.createElement("table");
  table.className = "w-full text-left text-sm";

  const thead = document.createElement("thead");
  const headRow = document.createElement("tr");
  for (const c of cols) {
    const th = document.createElement("th");
    th.className = "whitespace-nowrap px-3 py-2 font-mono text-xs text-white/50";
    th.textContent = c;
    headRow.append(th);
  }
  thead.append(headRow);

  const tbody = document.createElement("tbody");
  tbody.className = "divide-y divide-white/10";
  for (const r of rows) {
    const tr = document.createElement("tr");
    for (const c of cols) {
      const td = document.createElement("td");
      td.className = "px-3 py-2 align-top text-white/80";
      const v = r[c];
      if (v === null || v === undefined) {
        const span = document.createElement("span");
        span.className = "text-white/30";
        span.textContent = "NULL";
        td.append(span);
      } else {
        const s = Array.isArray(v) ? v.join(", ") : String(v);
        if (/^\/[\w\-/.]*$/.test(s)) {
          const a = document.createElement("a");
          a.className = "text-[#f3e5c0] underline";
          a.setAttribute("href", s);
          a.textContent = s;
          td.append(a);
        } else {
          td.textContent = s;
        }
      }
      tr.append(td);
    }
    tbody.append(tr);
  }

  table.append(thead, tbody);
  el.append(table);
}

export function initSqlConsole() {
  const root = document.getElementById("sql-console");
  if (!root) return;

  const startBtn = root.querySelector("[data-sql-start]");
  const panel = root.querySelector("[data-sql-panel]");
  const input = root.querySelector("[data-sql-input]");
  const runBtn = root.querySelector("[data-sql-run]");
  const status = root.querySelector("[data-sql-status]");
  const output = root.querySelector("[data-sql-output]");
  const log = (msg) => { status.textContent = msg; };

  const run = async () => {
    const sql = input.value.trim();
    if (!sql) return;
    runBtn.disabled = true;
    log("Počítám…");
    try {
      const conn = await dbPromise;
      const started = performance.now();
      const result = await conn.query(sql);
      const rows = result.toArray().map((r) => JSON.parse(JSON.stringify(r.toJSON(), (k, v) => (typeof v === "bigint" ? Number(v) : v))));
      renderTable(output, rows);
      log(`${rows.length} řádk(ů) za ${Math.round(performance.now() - started)} ms`);
    } catch (err) {
      output.replaceChildren();
      log(`Chyba: ${err.message}`);
    } finally {
      runBtn.disabled = false;
    }
  };

  startBtn.addEventListener("click", async () => {
    startBtn.disabled = true;
    panel.hidden = false;
    try {
      dbPromise = initDuckDb(log);
      await dbPromise;
      startBtn.remove();
      run();
    } catch (err) {
      log(
        "DuckDB se nepodařilo načíst (blokovaná CDN nebo nedostupný WebAssembly). " +
          "Data zůstávají ke stažení jako JSON odkazy níže.",
      );
      startBtn.disabled = false;
    }
  });

  runBtn.addEventListener("click", run);
  input.addEventListener("keydown", (e) => {
    if ((e.metaKey || e.ctrlKey) && e.key === "Enter") run();
  });
  root.querySelectorAll("[data-sql-example]").forEach((btn) => {
    btn.addEventListener("click", () => {
      input.value = btn.getAttribute("data-sql-example");
      if (dbPromise) run();
    });
  });
}
