#!/usr/bin/env node
/*
 * Guards the primary navigation, which is a GENERATED TREE
 * (data/generated/navigation.json, built by build-navigation.mjs from the
 * static skeleton in data/navigation.toml + data/dossiers.toml + the sections
 * that exist on disk).
 *
 * Two owner decisions are enforced here, both structural:
 *
 *  1. A person is never a top-level sidebar item. Entity dossiers hang under
 *     the "dossiers" item as their own subtrees — "macinka ani turek nejsou
 *     top level v sidebar, musí být generováno z dat" (site owner, 2026-07-30).
 *     The skeleton must therefore stay dossier-free: no slug, no person, no
 *     per-dossier registry item hand-written in data/navigation.toml.
 *
 *  2. An aggregate dossier never gets its own expandable subtree the way an
 *     entity dossier does — it stays a single, clearly labelled link, so it
 *     can't be mistaken for a third person (see AGENTS.md, "Entity dossiers
 *     vs. the aggregate view").
 *
 * Everything the tree links must also exist on disk.
 */
import { readFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadDossierRegistry } from "./lib/dossier-registry.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const NAV_TOML = join(ROOT, "data/navigation.toml");
const NAV_JSON = join(ROOT, "data/generated/navigation.json");

const errors = [];
const err = (msg) => errors.push(msg);

// --- 1. the hand-edited skeleton must stay dossier-free ---------------------
const skeleton = readFileSync(NAV_TOML, "utf8");
const registry = loadDossierRegistry();
for (const d of registry) {
  const re = new RegExp(`(^|[^a-z0-9-])${d.slug}([^a-z0-9-]|$)`, "m");
  // The skeleton legitimately mentions /dossiers/ (the catalog route); a
  // concrete dossier slug in it means the tree is being hand-written again.
  if (re.test(skeleton.replace(/^\s*#.*$/gm, ""))) {
    err(`data/navigation.toml mentions dossier slug "${d.slug}" — the skeleton must contain no dossier; the tree is generated by build-navigation.mjs.`);
  }
}

if (!existsSync(NAV_JSON)) {
  err(`${NAV_JSON} is missing — run \`npm run build:navigation\` before validating (npm run build does this for you).`);
  report();
}

const nav = JSON.parse(readFileSync(NAV_JSON, "utf8"));
const top = nav.items ?? [];
if (top.length === 0) err("data/generated/navigation.json: empty tree.");

const dossiersItem = top.find((i) => i.id === "dossiers");
if (!dossiersItem) err('Generated tree has no top-level "dossiers" item to hang the dossier subtrees on.');

// --- 2. no dossier at top level; every dossier present as a child ----------
const topIds = new Set(top.map((i) => i.id));
for (const d of registry) {
  if (topIds.has(d.slug) || top.some((i) => i.matchPrefix === `/dossiers/${d.slug}/`)) {
    err(`Dossier "${d.slug}" appears as a TOP-LEVEL sidebar item — dossiers must hang under "Dossiery" as a subtree.`);
  }
}
const children = dossiersItem?.children ?? [];
const childBySlug = new Map(children.map((c) => [c.id, c]));
for (const d of registry) {
  const node = childBySlug.get(d.slug);
  if (!node) {
    err(`Dossier "${d.slug}" is missing from the generated tree under "Dossiery".`);
    continue;
  }
  if (d.dossierType === "entity") {
    if (node.isAggregate) err(`Entity dossier "${d.slug}" is flagged as an aggregate in the generated tree.`);
    if ((node.children ?? []).length === 0) err(`Entity dossier "${d.slug}" has no registry children — its registries would be unreachable from the sidebar.`);
  } else {
    if (!node.isAggregate) err(`Aggregate dossier "${d.slug}" is not flagged as an aggregate — the template would render it like an entity dossier.`);
    if ((node.children ?? []).length > 0) err(`Aggregate dossier "${d.slug}" has an expandable subtree — an aggregate must never get its own registry tree.`);
  }
}

// --- 2b. concepts subtree: every concept page reachable from the sidebar ----
// The concept tree is generated the same way as the dossier tree, from
// data/concept-groups.toml + content/koncepty/*.md. A concept that exists on
// disk but is missing here is a page nobody can navigate to.
const conceptsItem = top.find((i) => i.id === "concepts");
if (conceptsItem) {
  const dir = join(ROOT, "content/koncepty");
  const slugs = readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "_index.md").map((f) => f.replace(/\.md$/, ""));
  const inTree = new Set();
  for (const g of conceptsItem.children) {
    if ((g.children ?? []).length === 0) err(`Concept group "${g.id}" has no pages in the generated tree — it would render an empty dropdown.`);
    if (!g.anchor) err(`Concept group "${g.id}" has no anchor — its sidebar entry would point at the bare /koncepty/ index.`);
    for (const c of g.children ?? []) inTree.add(c.id.replace(/^koncept-/, ""));
  }
  for (const slug of slugs) {
    if (!inTree.has(slug)) err(`Concept "${slug}" exists on disk but is missing from the sidebar tree.`);
  }
}

// --- 3. every linked route exists ------------------------------------------
const walk = (nodes, fn) => nodes.forEach((n) => { fn(n); walk(n.children ?? [], fn); });
walk(top, (node) => {
  if (!node.path) { err(`Nav node "${node.id}" has no path.`); return; }
  const m = node.path.match(/^@\/(.+)$/);
  if (!m) { err(`Nav node "${node.id}" has a non-content path "${node.path}".`); return; }
  if (!existsSync(join(ROOT, "content", m[1]))) {
    err(`Nav node "${node.id}" points at ${node.path}, which has no matching file at content/${m[1]}.`);
  }
  if (!node.label) err(`Nav node "${node.id}" has no label.`);
  if (!node.icon) err(`Nav node "${node.id}" has no icon.`);
});

report();

function report() {
  if (errors.length) {
    console.log(`${errors.length} error(s):`);
    for (const e of errors) console.log(`  ERROR ${e}`);
    process.exit(1);
  }
  const entityCount = registry.filter((d) => d.dossierType === "entity").length;
  const regLinks = (dossiersItem?.children ?? []).reduce((n, c) => n + (c.children ?? []).length, 0);
  console.log(
    `OK — generated navigation: ${top.length} top-level item(s), no dossier at top level; ` +
      `${entityCount} entity dossier(s) nested under "Dossiery" with ${regLinks} registry link(s); ` +
      `aggregate view(s) without a subtree; ` +
      `${(top.find((i) => i.id === "concepts")?.children ?? []).reduce((n, g) => n + (g.children ?? []).length, 0)} concept page(s) in the tree.`,
  );
}
